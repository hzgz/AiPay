const fs = require('fs')
const path = require('path')

const projectRoot = path.resolve(__dirname, '..')
const srcRoot = path.join(projectRoot, 'src')
const outputPath = path.join(srcRoot, 'utils', 'ui', 'iconify-loader.ts')

const collections = [
  ['ri', '@iconify-json/ri/icons.json'],
  ['solar', '@iconify-json/solar/icons.json'],
  ['line-md', '@iconify-json/line-md/icons.json'],
  ['iconamoon', '@iconify-json/iconamoon/icons.json'],
  ['svg-spinners', '@iconify-json/svg-spinners/icons.json']
]

const sourceExtensions = new Set(['.ts', '.tsx', '.js', '.jsx', '.vue'])
const usedIcons = new Map(collections.map(([prefix]) => [prefix, new Set()]))

function scanDirectory(dirPath) {
  const entries = fs.readdirSync(dirPath, { withFileTypes: true })

  for (const entry of entries) {
    const fullPath = path.join(dirPath, entry.name)

    if (entry.isDirectory()) {
      scanDirectory(fullPath)
      continue
    }

    if (!sourceExtensions.has(path.extname(entry.name))) {
      continue
    }

    const source = fs.readFileSync(fullPath, 'utf8')
    const matches = source.matchAll(
      /['"`]((?:ri|solar|line-md|iconamoon|svg-spinners):[A-Za-z0-9-]+)['"`]/g
    )

    for (const match of matches) {
      const [prefix, iconName] = match[1].split(':')
      usedIcons.get(prefix)?.add(iconName)
    }
  }
}

function pickIconFields(icon) {
  const subset = { body: icon.body }

  for (const key of ['left', 'top', 'width', 'height', 'rotate', 'hFlip', 'vFlip']) {
    if (icon[key] !== undefined) {
      subset[key] = icon[key]
    }
  }

  return subset
}

function createCollectionLiteral(prefix, packageName) {
  const collectionPath = require.resolve(packageName, { paths: [projectRoot] })
  const iconSet = require(collectionPath)
  const iconNames = Array.from(usedIcons.get(prefix) || []).sort()
  const icons = {}
  const aliases = {}

  for (const iconName of iconNames) {
    if (iconSet.icons[iconName]) {
      icons[iconName] = pickIconFields(iconSet.icons[iconName])
      continue
    }

    if (iconSet.aliases?.[iconName]) {
      const alias = { ...iconSet.aliases[iconName] }
      aliases[iconName] = alias

      if (iconSet.icons[alias.parent] && !icons[alias.parent]) {
        icons[alias.parent] = pickIconFields(iconSet.icons[alias.parent])
      }

      continue
    }

    throw new Error(`Icon not found: ${prefix}:${iconName}`)
  }

  const variableName = `${prefix.replace(/-/g, '')}Icons`
  const lines = [
    `const ${variableName} = {`,
    `  prefix: ${JSON.stringify(iconSet.prefix)},`
  ]

  if (iconSet.width !== undefined) {
    lines.push(`  width: ${JSON.stringify(iconSet.width)},`)
  }

  if (iconSet.height !== undefined) {
    lines.push(`  height: ${JSON.stringify(iconSet.height)},`)
  }

  lines.push('  icons: {')

  for (const [iconName, iconData] of Object.entries(icons)) {
    lines.push(`    ${JSON.stringify(iconName)}: ${JSON.stringify(iconData)},`)
  }

  lines.push('  },')

  if (Object.keys(aliases).length > 0) {
    lines.push('  aliases: {')

    for (const [iconName, aliasData] of Object.entries(aliases)) {
      lines.push(`    ${JSON.stringify(iconName)}: ${JSON.stringify(aliasData)},`)
    }

    lines.push('  },')
  }

  lines.push('}')

  return {
    variableName,
    lines
  }
}

scanDirectory(srcRoot)

const fileLines = [
  "import { addCollection } from '@iconify/vue'",
  '',
  '// Generated by scripts/generate-iconify-loader.cjs',
  '// Registers only the icon glyphs referenced in the local source tree.',
  '// This keeps the admin shell offline-capable without bundling whole icon packs.',
  ''
]

const variableNames = []

for (const [prefix, packageName] of collections) {
  const { variableName, lines } = createCollectionLiteral(prefix, packageName)
  variableNames.push(variableName)
  fileLines.push(...lines, '')
}

for (const variableName of variableNames) {
  fileLines.push(`addCollection(${variableName} as any)`)
}

fileLines.push('')

fs.writeFileSync(outputPath, fileLines.join('\n'), 'utf8')
console.log(`Generated ${path.relative(projectRoot, outputPath)}`)
